--TC02 — Boundary: bắt đầu đúng ngày booking trước kết thúc
WITH ROOM_SCHEDULE AS (
    SELECT
        R.ROOM_ID,
        MAX(B.CHECK_OUT_DATE) AS LAST_CHECK_OUT
    FROM ROOMS R
    JOIN BOOKINGS B
        ON R.ROOM_ID = B.ROOM_ID
    WHERE R.ROOM_NUMBER = '101'
      AND B.BOOKING_STATUS IN (
          'PENDING',
          'CONFIRMED',
          'CHECKED_IN'
      )
    GROUP BY R.ROOM_ID
)
SELECT
    ROOM_ID,
    LAST_CHECK_OUT,
    PKG_HOTEL_BOOKING.FN_IS_ROOM_AVAILABLE(
        ROOM_ID,
        LAST_CHECK_OUT,
        LAST_CHECK_OUT + 2,
        NULL
    ) AS IS_AVAILABLE
FROM ROOM_SCHEDULE;

--TC03 — Check-out nhỏ hơn Check-in
