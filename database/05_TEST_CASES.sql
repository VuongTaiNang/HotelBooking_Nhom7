SELECT
    B.BOOKING_ID,
    C.FULL_NAME,
    R.ROOM_NUMBER,
    B.CHECK_IN_DATE,
    B.CHECK_OUT_DATE,
    B.BOOKING_STATUS
FROM BOOKINGS B
JOIN CUSTOMERS C
    ON B.CUSTOMER_ID = C.CUSTOMER_ID
JOIN ROOMS R
    ON B.ROOM_ID = R.ROOM_ID
WHERE C.PHONE = '0901000003'
  AND R.ROOM_NUMBER = '103'
ORDER BY B.BOOKING_ID DESC;

BEGIN
