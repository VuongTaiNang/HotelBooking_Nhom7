-- Evidence: when was a room confirmed clean, and which DB account did it?
CREATE TABLE ROOM_HOUSEKEEPING_LOG (
    LOG_ID         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ROOM_ID        NUMBER NOT NULL,
    OLD_STATUS     VARCHAR2(30) NOT NULL,
    NEW_STATUS     VARCHAR2(30) NOT NULL,
    COMPLETED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_BY   VARCHAR2(128) NOT NULL,
    CONSTRAINT FK_RH_LOG_ROOM FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID)
);

-- Staff action: only CLEANING -> AVAILABLE, row locked until transaction commit.
CREATE OR REPLACE PROCEDURE SP_COMPLETE_ROOM_CLEANING (
    P_ROOM_ID IN ROOMS.ROOM_ID%TYPE
)
AS
    V_OLD_STATUS ROOMS.STATUS%TYPE;
BEGIN
    SELECT STATUS INTO V_OLD_STATUS
    FROM ROOMS
    WHERE ROOM_ID = P_ROOM_ID
    FOR UPDATE WAIT 5;

    IF V_OLD_STATUS <> 'CLEANING' THEN
        RAISE_APPLICATION_ERROR(-20120,
            'Room is not in CLEANING status. Only CLEANING -> AVAILABLE is allowed.');
    END IF;

    UPDATE ROOMS
    SET STATUS = 'AVAILABLE'
    WHERE ROOM_ID = P_ROOM_ID;

    INSERT INTO ROOM_HOUSEKEEPING_LOG (ROOM_ID, OLD_STATUS, NEW_STATUS, COMPLETED_BY)
    VALUES (P_ROOM_ID, V_OLD_STATUS, 'AVAILABLE', SYS_CONTEXT('USERENV','SESSION_USER'));

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20121, 'Room does not exist.');
END SP_COMPLETE_ROOM_CLEANING;
/

-- Database-level protection also applies if CHECK_IN is called directly via PL/SQL.
-- Keep SP_CHECK_IN as is; its existing booking status validations still apply.
CREATE OR REPLACE TRIGGER TRG_BLOCK_CHECKIN_UNREADY
BEFORE UPDATE OF BOOKING_STATUS ON BOOKINGS
FOR EACH ROW
WHEN (NEW.BOOKING_STATUS = 'CHECKED_IN')
DECLARE
    V_ROOM_STATUS ROOMS.STATUS%TYPE;
BEGIN
    IF :OLD.BOOKING_STATUS <> 'CHECKED_IN' THEN
        SELECT STATUS INTO V_ROOM_STATUS
        FROM ROOMS
        WHERE ROOM_ID = :NEW.ROOM_ID
        FOR UPDATE WAIT 5;

        IF V_ROOM_STATUS <> 'AVAILABLE' THEN
            RAISE_APPLICATION_ERROR(-20122,
                'Cannot check in: room must be AVAILABLE. Complete cleaning first.');
        END IF;
    END IF;
END TRG_BLOCK_CHECKIN_UNREADY;
/

