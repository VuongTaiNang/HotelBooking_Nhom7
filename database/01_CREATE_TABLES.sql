--table booking
CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    CUSTOMER_ID NUMBER NOT NULL,

    ROOM_ID NUMBER NOT NULL,

    CHECK_IN_DATE DATE NOT NULL,

    CHECK_OUT_DATE DATE NOT NULL,

    GUEST_COUNT NUMBER(2) NOT NULL,

    ROOM_RATE NUMBER(12,2) NOT NULL,

    BOOKING_STATUS VARCHAR2(20)
        DEFAULT 'PENDING'
        NOT NULL,

    CREATED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    UPDATED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_BOOKINGS
        PRIMARY KEY (BOOKING_ID),

    CONSTRAINT FK_BOOKINGS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID),

    CONSTRAINT FK_BOOKINGS_ROOM
        FOREIGN KEY (ROOM_ID)
        REFERENCES ROOMS(ROOM_ID),

    CONSTRAINT CK_BOOKINGS_DATES
        CHECK (CHECK_OUT_DATE > CHECK_IN_DATE),

    CONSTRAINT CK_BOOKINGS_GUEST_COUNT
        CHECK (GUEST_COUNT > 0),

    CONSTRAINT CK_BOOKINGS_ROOM_RATE
        CHECK (ROOM_RATE >= 0),

    CONSTRAINT CK_BOOKINGS_STATUS
        CHECK (
            BOOKING_STATUS IN (
                'PENDING',
                'CONFIRMED',
                'CHECKED_IN',
                'CHECKED_OUT',
                'CANCELLED'
            )
        )
);



--table service
CREATE TABLE SERVICES (
    SERVICE_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    SERVICE_NAME VARCHAR2(100) NOT NULL,

    DESCRIPTION VARCHAR2(500),

    UNIT_PRICE NUMBER(12,2) NOT NULL,

    STATUS VARCHAR2(20)
        DEFAULT 'ACTIVE'
        NOT NULL,

    CONSTRAINT PK_SERVICES
        PRIMARY KEY (SERVICE_ID),

    CONSTRAINT UQ_SERVICES_NAME
        UNIQUE (SERVICE_NAME),

    CONSTRAINT CK_SERVICES_PRICE
        CHECK (UNIT_PRICE >= 0),

    CONSTRAINT CK_SERVICES_STATUS
        CHECK (
            STATUS IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


--table booking_service
CREATE TABLE BOOKING_SERVICES (
    BOOKING_SERVICE_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    BOOKING_ID NUMBER NOT NULL,

    SERVICE_ID NUMBER NOT NULL,

    QUANTITY NUMBER(5)
        DEFAULT 1
        NOT NULL,

    UNIT_PRICE NUMBER(12,2) NOT NULL,

    USED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_BOOKING_SERVICES
        PRIMARY KEY (BOOKING_SERVICE_ID),

    CONSTRAINT FK_BOOKING_SERVICES_BOOKING
        FOREIGN KEY (BOOKING_ID)
        REFERENCES BOOKINGS(BOOKING_ID),

    CONSTRAINT FK_BOOKING_SERVICES_SERVICE
        FOREIGN KEY (SERVICE_ID)
        REFERENCES SERVICES(SERVICE_ID),

    CONSTRAINT CK_BOOKING_SERVICES_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT CK_BOOKING_SERVICES_PRICE
        CHECK (UNIT_PRICE >= 0)
);


--table payment
CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    BOOKING_ID NUMBER NOT NULL,

    AMOUNT NUMBER(12,2) NOT NULL,

    PAYMENT_METHOD VARCHAR2(20) NOT NULL,

    PAYMENT_STATUS VARCHAR2(20)
        DEFAULT 'PENDING'
        NOT NULL,

    REFERENCE_CODE VARCHAR2(100),

    PAYMENT_DATE TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_PAYMENTS
        PRIMARY KEY (PAYMENT_ID),

    CONSTRAINT FK_PAYMENTS_BOOKING
        FOREIGN KEY (BOOKING_ID)
        REFERENCES BOOKINGS(BOOKING_ID),

    CONSTRAINT CK_PAYMENTS_AMOUNT
        CHECK (AMOUNT > 0),

    CONSTRAINT CK_PAYMENTS_METHOD
        CHECK (
            PAYMENT_METHOD IN (
                'CASH',
                'CARD',
                'BANK_TRANSFER'
            )
        ),

    CONSTRAINT CK_PAYMENTS_STATUS
        CHECK (
            PAYMENT_STATUS IN (
                'PENDING',
                'COMPLETED',
                'FAILED',
                'REFUNDED'
            )
        )
);


--table booking_audit
CREATE TABLE BOOKING_AUDIT (
    AUDIT_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    BOOKING_ID NUMBER,

    ACTION_TYPE VARCHAR2(10) NOT NULL,

    OLD_ROOM_ID NUMBER,
    NEW_ROOM_ID NUMBER,

    OLD_CHECK_IN_DATE DATE,
    NEW_CHECK_IN_DATE DATE,

    OLD_CHECK_OUT_DATE DATE,
    NEW_CHECK_OUT_DATE DATE,

    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20),

    CHANGED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CHANGED_BY VARCHAR2(100),

    CONSTRAINT PK_BOOKING_AUDIT
        PRIMARY KEY (AUDIT_ID),

    CONSTRAINT CK_BOOKING_AUDIT_ACTION
        CHECK (
            ACTION_TYPE IN (
                'INSERT',
                'UPDATE',
                'DELETE'
            )
        )
);




