--table customer
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    FULL_NAME VARCHAR2(100) NOT NULL,

    PHONE VARCHAR2(15) NOT NULL,

    EMAIL VARCHAR2(120),

    IDENTITY_NUMBER VARCHAR2(20),

    DATE_OF_BIRTH DATE,

    STATUS VARCHAR2(20)
        DEFAULT 'ACTIVE'
        NOT NULL,

    CREATED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_CUSTOMERS
        PRIMARY KEY (CUSTOMER_ID),

    CONSTRAINT UQ_CUSTOMERS_PHONE
        UNIQUE (PHONE),

    CONSTRAINT UQ_CUSTOMERS_EMAIL
        UNIQUE (EMAIL),

    CONSTRAINT UQ_CUSTOMERS_IDENTITY
        UNIQUE (IDENTITY_NUMBER),

    CONSTRAINT CK_CUSTOMERS_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


--table room_types
CREATE TABLE ROOM_TYPES (
    ROOM_TYPE_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    TYPE_NAME VARCHAR2(50) NOT NULL,

    DESCRIPTION VARCHAR2(500),

    PRICE_PER_NIGHT NUMBER(12,2) NOT NULL,

    MAX_GUESTS NUMBER(2) NOT NULL,

    CREATED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT PK_ROOM_TYPES
        PRIMARY KEY (ROOM_TYPE_ID),

    CONSTRAINT UQ_ROOM_TYPES_NAME
        UNIQUE (TYPE_NAME),

    CONSTRAINT CK_ROOM_TYPES_PRICE
        CHECK (PRICE_PER_NIGHT > 0),

    CONSTRAINT CK_ROOM_TYPES_MAX_GUESTS
        CHECK (MAX_GUESTS > 0)
);


--table rooms
CREATE TABLE ROOMS (
    ROOM_ID NUMBER
        GENERATED ALWAYS AS IDENTITY,

    ROOM_NUMBER VARCHAR2(10) NOT NULL,

    ROOM_TYPE_ID NUMBER NOT NULL,

    FLOOR_NUMBER NUMBER(2),

    STATUS VARCHAR2(20)
        DEFAULT 'AVAILABLE'
        NOT NULL,

    CONSTRAINT PK_ROOMS
        PRIMARY KEY (ROOM_ID),

    CONSTRAINT UQ_ROOMS_NUMBER
        UNIQUE (ROOM_NUMBER),

    CONSTRAINT CK_ROOMS_STATUS
        CHECK (
            STATUS IN (
                'AVAILABLE',
                'OCCUPIED',
                'CLEANING',
                'MAINTENANCE'
            )
        ),

    CONSTRAINT FK_ROOMS_ROOM_TYPE
        FOREIGN KEY (ROOM_TYPE_ID)
        REFERENCES ROOM_TYPES(ROOM_TYPE_ID)
);

