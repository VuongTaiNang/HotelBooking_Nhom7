SELECT
    R.ROOM_ID,
    R.ROOM_NUMBER,
    RT.TYPE_NAME,
    RT.PRICE_PER_NIGHT,
    RT.MAX_GUESTS
FROM ROOMS R
JOIN ROOM_TYPES RT
    ON R.ROOM_TYPE_ID = RT.ROOM_TYPE_ID
WHERE R.STATUS <> 'MAINTENANCE'

  AND RT.MAX_GUESTS >= 2

  AND NOT EXISTS (
      SELECT 1
      FROM BOOKINGS B
      WHERE B.ROOM_ID = R.ROOM_ID

        AND B.BOOKING_STATUS IN (
            'PENDING',
            'CONFIRMED',
            'CHECKED_IN'
        )

        AND DATE '2026-11-15' < B.CHECK_OUT_DATE
        AND DATE '2026-11-18' > B.CHECK_IN_DATE
  )
ORDER BY RT.PRICE_PER_NIGHT;



