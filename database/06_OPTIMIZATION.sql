INSERT INTO BOOKINGS (
    CUSTOMER_ID,
    ROOM_ID,
    CHECK_IN_DATE,
    CHECK_OUT_DATE,
    GUEST_COUNT,
    ROOM_RATE,
    BOOKING_STATUS,
    CREATED_AT,
    UPDATED_AT
)
WITH GEN AS (
    SELECT LEVEL AS N
    FROM DUAL
    CONNECT BY LEVEL <= 5000
),

CUSTOMER_LIST AS (
    SELECT
        CUSTOMER_ID,
        ROW_NUMBER() OVER (
            ORDER BY CUSTOMER_ID
        ) AS RN
    FROM CUSTOMERS
),

ROOM_LIST AS (
    SELECT
        R.ROOM_ID,
        RT.PRICE_PER_NIGHT,
        ROW_NUMBER() OVER (
            ORDER BY R.ROOM_ID
        ) AS RN
    FROM ROOMS R
    JOIN ROOM_TYPES RT
        ON R.ROOM_TYPE_ID = RT.ROOM_TYPE_ID
)



SELECT
    C.CUSTOMER_ID,

    R.ROOM_ID,

    DATE '2020-01-01'
        + MOD(G.N - 1, 300),

    DATE '2020-01-01'
        + MOD(G.N - 1, 300)
        + 1,

    1,

    R.PRICE_PER_NIGHT,

    'CHECKED_OUT',

    TIMESTAMP '2020-01-01 00:00:00'
        + NUMTODSINTERVAL(G.N, 'SECOND'),

    TIMESTAMP '2020-01-01 00:00:00'
        + NUMTODSINTERVAL(G.N, 'SECOND')

FROM GEN G

JOIN CUSTOMER_LIST C
    ON C.RN = MOD(G.N - 1, 8) + 1

JOIN ROOM_LIST R
    ON R.RN = MOD(G.N - 1, 12) + 1;
COMMIT;

